import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {chromium} from 'playwright-core'

const browser=await chromium.launch({channel:'chrome'})
try {
  const page=await browser.newPage({viewport:{width:1440,height:900}})
  page.setDefaultTimeout(12000)
  const faults=[],external=[]
  page.on('pageerror',e=>faults.push(e.message))
  page.on('request',r=>{if(/^https?:/.test(r.url())&&new URL(r.url()).hostname!=='localhost')external.push(r.url())})
  const button=name=>page.getByRole('button',{name,exact:true})
  const run=async()=>{
    const response=page.waitForResponse(r=>r.url().endsWith('/intelligence/debug')&&r.request().method()==='POST')
    await button('Run comparison').click()
    const r=await response
    assert.equal(r.status(),200)
    await page.getByRole('heading',{name:/Release gate ·/}).waitFor()
    return r.json()
  }
  await page.goto('http://localhost:5173/')
  await page.getByRole('link',{name:'Open Retrieval Debugger'}).click()
  await page.getByLabel('Search query',{exact:true}).fill('telescope light draft')
  await page.route('**/api/v1/health',route=>route.fulfill({status:503,body:''}))
  await page.getByRole('button',{name:'Retry connection'}).waitFor()
  assert.equal(await page.getByLabel('Search query',{exact:true}).inputValue(),'telescope light draft')
  await page.unroute('**/api/v1/health')
  await page.getByRole('button',{name:'Retry connection'}).click()
  await page.getByText('API connected',{exact:true}).waitFor()
  assert.equal(await page.getByLabel('Search query',{exact:true}).inputValue(),'telescope light draft')
  await page.getByLabel('Search query',{exact:true}).fill('telescope light')
  await page.getByLabel('Candidate method').selectOption('dense')
  let r=await run()
  assert.equal(r.gate,'PASS');assert.equal(r.summary.dense.recall,1)
  await page.getByText(/Expected relevant documents/).click()
  await page.getByRole('checkbox',{name:/^#6 ·/}).uncheck()
  await page.getByRole('checkbox',{name:/^#24 ·/}).check()
  await page.getByLabel('Minimum candidate Recall@K').fill('1')
  r=await run()
  assert.deepEqual(r.tasks[0].methods.dense.missed,[24]);assert.equal(r.gate,'BLOCK')
  await button('Add search task').click()
  await page.getByLabel('Search query',{exact:true}).fill('xylolith')
  r=await run()
  assert.equal(r.tasks.length,2);assert.equal(r.tasks[1].change,'unlabeled')
  assert.equal(r.tasks[1].methods.dense.recall,null);assert.equal(r.summary.dense.labeled,1)
  await page.getByLabel('Inspect task').selectOption('1')
  await page.getByText(/Relevance judgments required/).waitFor()
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await page.getByRole('link',{name:'Open Data Foundry',exact:true}).click()
  await page.getByLabel('Dataset file').setInputFiles({name:'engineering.csv',mimeType:'text/csv',buffer:Buffer.from('title,body\na,xylolith\nb,telescope light\nc,ocean tide\n')})
  await page.getByLabel('Text column').selectOption('1')
  await button('Debug this dataset').click()
  await page.getByLabel('Search query',{exact:true}).fill('xylolith')
  await page.getByText(/Expected relevant documents/).click()
  await page.getByRole('checkbox',{name:/^#1 ·/}).check()
  await page.getByLabel('Candidate method').selectOption('fusion')
  await page.getByLabel('Require measured candidate geometry within limits').uncheck()
  r=await run()
  assert.equal(r.gate,'PASS');assert.equal(r.represented,2);assert.equal(r.tasks[0].change,'improved')
  assert.equal(r.summary.dense.recall,0);assert.equal(r.summary.fusion.recall,1)
  assert.deepEqual(r.tasks[0].rank_changes,[{id:1,baseline:null,candidate:1}])
  const downloading=page.waitForEvent('download')
  await button('Export reproducible report').click()
  const saved=JSON.parse(await readFile(await (await downloading).path(),'utf8'))
  assert.equal(saved.source.text_column,'body');assert.match(saved.source.file_sha256,/^[a-f0-9]{64}$/)
  const replay=await page.request.post('http://localhost:5173/api/v1/intelligence/debug',{headers:{'X-Vector-X-Client':'foundry'},data:saved.replay})
  assert.deepEqual(await replay.json(),r)
  await button('Delete dataset').click()
  await button('Choose file').waitFor();assert.equal(await button('Export reproducible report').count(),0)
  assert.deepEqual(faults,[]);assert.deepEqual(external,[])
  console.log('FOCUS: calibration pass, labeled miss, unlabeled preview, 390px layout, private import, lexical fallback, gate, exact JSON replay and deletion passed.')
} finally {await browser.close()}
