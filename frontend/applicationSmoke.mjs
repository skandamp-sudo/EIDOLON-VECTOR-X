import assert from 'node:assert/strict'

// Exercise the same walkthrough against local or hosted application entry points.
export async function checkApplications(page, origin) {
  await page.goto(origin+'/#applications')
  await page.getByRole('heading',{name:'Knowledge exploration'}).waitFor()
  const step=page.getByLabel('Walkthrough step')
  await page.getByLabel('Inspect document').selectOption({index:2})
  await page.getByRole('heading',{name:'Related documents'}).waitFor()
  await step.selectOption('1')
  await page.getByRole('button',{name:'Astronomy',exact:true}).click()
  await page.getByRole('heading',{name:'Astronomy',exact:true}).waitFor()
  await step.selectOption('2')
  await page.getByRole('heading',{name:'Category review'}).waitFor()
  const mismatch=page.getByRole('button',{name:'Unreviewed mirror blank',exact:true}).last()
  await mismatch.click()
  await step.selectOption('3')
  const baseline=await page.getByRole('heading',{name:'Static baseline'}).locator('..').getByRole('list').innerText()
  await page.getByRole('button',{name:'Save candidate preference'}).click()
  await page.getByText(/1 saved interactions/).waitFor()
  await page.getByRole('button',{name:'Roll back last save'}).click()
  await page.getByText('0 saved interactions').waitFor()
  assert.equal(await page.getByRole('heading',{name:'Adaptive candidates'}).locator('..').getByRole('list').innerText(),baseline)
  await step.selectOption('4')
  await page.getByRole('button',{name:'Reject recommendation'}).click()
  assert.equal(await page.getByRole('button',{name:'Approve recommendation'}).isDisabled(),true)
  await page.getByRole('button',{name:'Restore recommendation'}).click()
  await page.getByRole('button',{name:'Approve recommendation'}).click()
  await page.getByRole('button',{name:'Undo selection'}).click()
  await page.setViewportSize({width:390,height:844})
  await step.selectOption('5')
  await page.getByLabel('Research encoder').selectOption('minilm')
  await page.getByText(/QASPER · within-paper retrieval/).waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
}
